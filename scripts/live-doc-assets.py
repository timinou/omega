#!/usr/bin/env python3
"""Regenerate src/omega/live_doc/assets.bl from client.js and client.css.

Source bundles carry Beam Lisp namespaces only, so the in-place editor's
browser assets travel as string constants. test/live_doc_test.bl fails when
this file is out of date with its sources.
"""
import pathlib
root = pathlib.Path(__file__).resolve().parent.parent / "src/omega/live_doc"
def lit(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'
js = (root / "client.js").read_text()
css = (root / "client.css").read_text()
(root / "assets.bl").write_text(
    ";; GENERATED by scripts/live-doc-assets.py from client.js and client.css. Do not edit.\n"
    "(ns omega.live-doc.assets)\n"
    f"(def client-js {lit(js)})\n"
    f"(def client-css {lit(css)})\n")
