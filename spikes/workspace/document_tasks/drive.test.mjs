import test from 'node:test';
import assert from 'node:assert/strict';
import {pathToFileURL} from 'node:url';
import path from 'node:path';
const out=path.resolve(process.env.BLED_OUT||'vendor/bl-ed/web/out');
const load=n=>import(pathToFileURL(path.join(out,n+'.mjs')));
const R=await load('rt'),M=await load('ed.main'),P=await load('ed.pkg'),D=await load('document-tasks.main'),W=await load('ws.main');
const K=R.kw,g=(m,k)=>m?.get(K(k),null),map=R.hashMap;
test('generic document task commands capture source, use task/open, and unuse exactly',()=>{
 const original=M.d_boot('#+TITLE: Ordinary\n* Section\nPlain text\n','work:project/ordinary.bl.org');
 const workspace=P.d_use(original,W.d_bl_package);
 assert.equal(R.printStr(P.d_keymap(P.d_use(workspace,D.d_bl_package))),R.printStr(P.d_keymap(workspace)),'existing navigation keys retain their meanings');
 let ed=P.d_use(original,D.d_bl_package);
 const removed=P.d_unuse(ed,'document-tasks');
 for(const key of ['text','sels','saved-text','doc','mode','view','user-commands','user-keys'])assert.equal(R.printStr(g(removed,key)),R.printStr(g(original,key)),key);
 ed=M.d_handle(ed,map(K('type'),K('command'),K('command'),K('document-tasks/section')));
 let [next,fx]=M.d_take_effects(ed).toArray();ed=next;
 const request=fx.toArray().find(f=>g(f,'intent')==='document/context');
 assert.equal(g(g(request,'args'),'scope'),'section');assert.equal(g(g(request,'args'),'path'),'work:project/ordinary.bl.org');
 const selection=map(K('path'),'document:doc-1',K('scope'),'section',K('label'),'Section',K('text'),'* Section\nPlain text',K('rev'),'0',K('start'),1,K('end'),3);
 ed=M.d_handle(ed,map(K('type'),K('intent-result'),K('then'),K('document-tasks/context'),K('ok?'),true,K('data'),map(K('selection'),selection)));
 assert.match(g(g(ed,'minibuf'),'prompt'),/Work on Section/);
 const cancelled=P.d_unuse(ed,'document-tasks');assert.equal(g(cancelled,'minibuf'),null,'unuse cancels its owned prompt');
 ed=M.d_handle(ed,map(K('type'),K('text'),K('text'),'Improve this'));
 ed=M.d_handle(ed,map(K('type'),K('key'),K('key'),'Enter'));
 fx=M.d_take_effects(ed).toArray()[1].toArray();
 const opened=fx.find(f=>g(f,'intent')==='task/open');assert.ok(opened);
 assert.equal(g(g(opened,'args'),'goal'),'Improve this');assert.equal(g(g(opened,'args'),'selection'),selection);
 assert.equal(g(g(opened,'args'),'scope'),null,'origin does not constrain execution');
});
